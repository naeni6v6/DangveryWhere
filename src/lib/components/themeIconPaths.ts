/**
 * 지도 마커처럼 스벨트 밖에서 아이콘이 필요한 자리에 쓰는 SVG 조각.
 * 색은 넘겨받은 자리에서 currentColor 로 정합니다.
 */
export function themeIconSvg(theme: Theme, size: number, strokeWidth = 1.9): string {
  const paths = themeIconPaths[theme].map((d) => `<path d="${d}"/>`).join('');
  return (
    `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor"` +
    ` stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round"` +
    ` aria-hidden="true" focusable="false">${paths}</svg>`
  );
}
